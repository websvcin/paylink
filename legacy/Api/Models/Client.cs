using System.ComponentModel.DataAnnotations;
using Api.Constants;

namespace Api.Models;

public class Client
{
    public int? Id { get; set; } // Auto-incremented primary key

    [Required]
    public string Name { get; set; }

    [Required]
    public string OriginUrl { get; set; }

    public DateTime? CreatedAt { get; set; }

    [Required]
    public string ClientId { get; set; } // GUID stored as CHAR(36), auto-generated by DB

    [Required]
    public string UpiId { get; set; } // GUID stored as CHAR(36), auto-generated by DB
}
