// Turns the OpenAPI documents in static/openapi/ into the API reference pages in docs/api-reference/.
// Refresh the documents from a running PayLink, then regenerate:
//   for d in payments tenant platform; do curl -s https://pay.example.com/docs/api/$d/openapi.json -o static/openapi/$d.json; done
//   node scripts/generate-api-reference.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const pages = [
  { doc: 'payments', file: 'payments-api.md', title: 'Payments API reference', position: 2,
    intro: 'Routes under `/api/v1`, for a merchant\'s server. Authenticate with a secret key: `Authorization: Bearer sk_test_…` or `sk_live_…`. A platform key with *Act for tenants* can call them for a tenant with `PayLink-Tenant: {slug}` and `PayLink-Mode: test|live`. Guide: [Payments API](../integrate/payments-api.md).' },
  { doc: 'tenant', file: 'tenant-api.md', title: 'Tenant API reference', position: 3,
    intro: 'Routes under `/api/tenant`, for scripts that run a tenant\'s console. Authenticate with a developer key: `Authorization: Bearer tdk_…`; each route needs the capability shown. Choose test or live data with `?livemode=true|false` (default `false`). A platform key with *Act for tenants* can call every route for a tenant with `PayLink-Tenant: {slug}`. Guide: [automation API](../automation/tenant-api.md).' },
  { doc: 'platform', file: 'platform-api.md', title: 'Platform API reference', position: 4,
    intro: 'Routes under `/api/admin`, for running PayLink itself. Authenticate with a platform key: `Authorization: Bearer pdk_…`; each route needs the capability shown. Guide: [platform API](../automation/platform-api.md).' },
];

const esc = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\r?\n+/g, ' ').trim();

function resolve(spec, schema) {
  if (schema?.$ref) return resolve(spec, spec.components.schemas[schema.$ref.split('/').pop()]);
  return schema ?? {};
}

function typeOf(spec, schema) {
  if (!schema) return '';
  if (schema.$ref) {
    const target = resolve(spec, schema);
    return target.properties ? 'object' : typeOf(spec, target);
  }
  if (schema.type === 'array') return `array of ${typeOf(spec, schema.items) || 'any'}`;
  if (schema.type === 'object' && schema.additionalProperties) return `map of ${typeOf(spec, schema.additionalProperties) || 'string'}`;
  return [schema.type, schema.format].filter(Boolean).join(' ');
}

function fields(spec, schema, prefix = '', depth = 0, out = []) {
  const s = resolve(spec, schema);
  for (const [name, prop] of Object.entries(s.properties ?? {})) {
    const full = prefix + name;
    out.push(`| \`${full}\` | ${esc(typeOf(spec, prop))} | ${esc(resolve(spec, prop).description ?? prop.description)} |`);
    const inner = prop.type === 'array' ? prop.items : prop;
    if (depth < 2 && resolve(spec, inner).properties && (inner?.$ref || inner?.properties)) fields(spec, inner, `${full}${prop.type === 'array' ? '[]' : ''}.`, depth + 1, out);
  }
  return out;
}

for (const page of pages) {
  const spec = JSON.parse(fs.readFileSync(path.join(root, 'static/openapi', `${page.doc}.json`), 'utf8'));
  const lines = [
    '---', `sidebar_position: ${page.position}`, `title: ${page.title}`, '---', '',
    '<!-- Generated by scripts/generate-api-reference.mjs from static/openapi/. Edit the API\'s XML comments, not this file. -->', '',
    `# ${page.title}`, '', page.intro, '',
    `OpenAPI document: [${page.doc}.json](pathname:///openapi/${page.doc}.json). Every PayLink also serves it at \`/docs/api/${page.doc}/openapi.json\`, with Swagger UI at \`/docs/api\`.`, '',
  ];
  const groups = new Map();
  for (const [p, ops] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(ops)) {
      const group = p.split('/')[3] ?? '';
      if (!groups.has(group)) groups.set(group, []);
      groups.get(group).push({ p, method, op });
    }
  }
  for (const [group, ops] of groups) {
    lines.push(`## ${group ? `/${group}` : 'Root'}`, '');
    for (const { p, method, op } of ops) {
      lines.push(`### \`${method.toUpperCase()} ${p}\``, '');
      if (op.summary) lines.push(op.summary.trim(), '');
      if (op.description) lines.push(op.description.replace(/\n\n/g, ' ').trim(), '');
      const params = (op.parameters ?? []).filter(x => x.in !== 'header');
      if (params.length) {
        lines.push('| Parameter | In | Type | |', '|---|---|---|---|');
        for (const x of params) lines.push(`| \`${x.name}\` | ${x.in} | ${esc(typeOf(spec, x.schema))} | ${x.required ? 'required' : ''} ${esc(x.description)} |`);
        lines.push('');
      }
      const body = op.requestBody?.content;
      if (body) {
        const [type, media] = Object.entries(body)[0];
        const rows = media.schema ? fields(spec, media.schema) : [];
        const kinds = Object.keys(body).filter(t => !/^(text\/json|application\/\*\+json)$/.test(t)).map(t => t === 'application/json' ? 'JSON' : `\`${t}\``);
        lines.push(`Body (${kinds.join(' or ')}):`, '');
        if (rows.length) lines.push('| Field | Type | |', '|---|---|---|', ...rows, '');
        else if (type === 'text/csv') lines.push('The file itself.', '');
      }
    }
  }
  fs.writeFileSync(path.join(root, 'docs/api-reference', page.file), lines.join('\n'));
  console.log(page.file, [...groups.values()].reduce((n, g) => n + g.length, 0), 'operations');
}
